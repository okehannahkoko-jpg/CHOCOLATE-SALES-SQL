alter table sales 
Rename column `Boxes shipped`to Boxes_shipped;
select *
from sales
where sales_person is null
or country is null
or product is null
or amount is null;

--- Total Revenue
select sum(Amount) as total_revenue
from sales;


--- total boxes sold
select sum(boxes_shipped) as total_boxes_sold
from sales;

--- Average revenue per box
select sum(amount)/sum(boxes_shipped) as revenue_per_box
from sales;

--- Top 10 products by revenue
select product,sum(amount) as revenue 
from sales 
group by product 
order by revenue desc
limit 10; 

--- Top 10 products by boxes shipped
select product,sum(Boxes_shipped) as total_boxes
from sales
group by product 
order by total_boxes desc
limit 10;

--- most profitable products (high revenue per boxes shipped)
select product,sum(Amount) / sum(Boxes_shipped)as revenue_per_box
from sales
group by product
order by revenue_per_box desc
limit 10;

--- Least profitable products (low revenue per boxes shipped)
select product,sum(Amount) / sum(Boxes_shipped)as revenue_per_box
from sales
group by product
order by revenue_per_box asc
limit 10;

--- sales person insights 
--- revenue generated by each salesperson
select sales_person,sum(amount) as total_revenue
